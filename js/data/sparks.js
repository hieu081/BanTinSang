/** Trả về chỉ số thẻ cố định theo ngày hiện tại (đổi mới mỗi ngày theo giờ địa phương) */
export function dailySparkIndex(date = new Date()) {
  const dayNum = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000);
  return ((dayNum % SPARKS.length) + SPARKS.length) % SPARKS.length;
}
